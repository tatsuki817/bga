/**
 * 16タイプ = 通常時の優位スタイル × プレッシャー時の優位スタイル。
 * コードは "SD" のように「通常→プレッシャー」の順で2文字。
 */
export type TypeCode = `${StyleId}${StyleId}`;

export interface TypeDef {
  code: TypeCode;
  normal: StyleId;
  pressure: StyleId;
  /** 愛称 */
  name: string;
  /** 一言キャッチ */
  catch: string;
  /** 概要（2〜3文） */
  summary: string;
  /** 行動指針（3つ） */
  guidelines: string[];
}

const T = (
  code: TypeCode,
  name: string,
  catchLine: string,
  summary: string,
  guidelines: string[],
): TypeDef => ({
  code,
  normal: code[0] as StyleId,
  pressure: code[1] as StyleId,
  name,
  catch: catchLine,
  summary,
  guidelines,
});

